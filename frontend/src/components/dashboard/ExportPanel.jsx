import { useState } from 'react';
import { Download, FileText, FileSpreadsheet } from 'lucide-react';
import { useDashboard } from '../../context/DashboardContext';

function downloadFile(content, filename, mimeType) {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);
}

function flattenAlerts(alerts) {
  return alerts.map((a) => ({
    cell_id: a.cell_id ?? '',
    timestamp: a.timestamp ?? '',
    issue_type: a.issue_type ?? '',
    severity: a.severity ?? '',
    priority: a.priority ?? '',
    causes: Array.isArray(a.causes) ? a.causes.join('; ') : a.causes ?? '',
    recommendations: Array.isArray(a.recommendations) ? a.recommendations.join('; ') : a.recommendations ?? '',
    ...Object.fromEntries(
      Object.entries(a.kpis || {}).map(([k, v]) => [`kpi_${k}`, v])
    ),
  }));
}

function toCsv(rows) {
  if (!rows.length) return '';
  const headers = Object.keys(rows[0]);
  const lines = [
    headers.join(','),
    ...rows.map((r) =>
      headers.map((h) => {
        const v = r[h];
        if (v == null) return '';
        const s = String(v);
        return s.includes(',') || s.includes('"') || s.includes('\n')
          ? `"${s.replace(/"/g, '""')}"`
          : s;
      }).join(',')
    ),
  ];
  return lines.join('\n');
}

export default function ExportPanel() {
  const { overview, diagnosticAlerts, diagnosticSummary, selectedBoId } = useDashboard();
  const [exported, setExported] = useState(null);

  const handleExportCSV = (type) => {
    const ts = new Date().toISOString().slice(0, 19).replace(/[:]/g, '-');
    const boLabel = selectedBoId || 'ALL';

    if (type === 'alerts') {
      const rows = flattenAlerts(diagnosticAlerts || []);
      if (!rows.length) return;
      downloadFile(toCsv(rows), `qos_alerts_${boLabel}_${ts}.csv`, 'text/csv');
    } else if (type === 'kpis') {
      const trends = overview?.trends || [];
      if (!trends.length) return;
      downloadFile(toCsv(trends), `qos_kpis_${boLabel}_${ts}.csv`, 'text/csv');
    } else if (type === 'zones') {
      const zones = overview?.zones || [];
      if (!zones.length) return;
      downloadFile(toCsv(zones), `qos_zones_${boLabel}_${ts}.csv`, 'text/csv');
    }

    setExported(type);
    setTimeout(() => setExported(null), 2000);
  };

  const handleExportReport = () => {
    const ts = new Date().toISOString().slice(0, 19);
    const boLabel = selectedBoId || 'ALL';
    const summary = diagnosticSummary || {};
    const bo1 = overview?.bo1 || {};
    const bo2 = overview?.bo2 || {};
    const bo3 = overview?.bo3 || {};

    const report = `QoS BUDDY - DIAGNOSTIC REPORT
========================================
Generated: ${ts}
Business Objective: ${boLabel}

SUMMARY (24h)
---
Total Alerts: ${summary.total_alerts ?? 'N/A'}
Critical: ${summary.critical ?? 'N/A'}
High: ${summary.high ?? 'N/A'}
Medium: ${summary.medium ?? 'N/A'}
Cells Monitored: ${summary.cells_monitored ?? 'N/A'}
Cells with Issues: ${summary.cells_with_issues ?? 'N/A'}

BO1 - ANOMALY DETECTION
---
Records Analyzed: ${bo1.records ?? 'N/A'}
Anomalies Detected: ${bo1.anomalies ?? 'N/A'}
Anomaly Rate: ${bo1.anomaly_rate_pct ?? 'N/A'}%
High Risk Cells: ${bo1.high_risk_cells ?? 'N/A'}

BO2 - SLA MONITORING
---
Avg SLA Breach Risk: ${bo2.avg_sla_breach_risk ?? 'N/A'}
High SLA Risk Count: ${bo2.high_sla_risk_count ?? 'N/A'}
Avg MOS: ${bo2.avg_mos ?? 'N/A'}
Low MOS Count: ${bo2.low_mos_count ?? 'N/A'}

BO3 - CAPEX SCORING
---
Avg CAPEX Score: ${bo3.avg_capex_score ?? 'N/A'}
Urgent Zones: ${bo3.urgent_count ?? 'N/A'}
Critical Risk Zones: ${bo3.critical_risk_count ?? 'N/A'}

ISSUE BREAKDOWN
---
${Object.entries(summary.issue_breakdown || {}).map(([k, v]) => `  ${k}: ${v}`).join('\n') || '  No data'}

TOP ALERTS
---
${(summary.top_alerts || []).slice(0, 5).map((a, i) =>
  `  ${i + 1}. [${a.severity}] ${a.issue_type} — Cell: ${a.cell_id}\n     Cause: ${(a.causes || [])[0] || 'N/A'}\n     Action: ${(a.recommendations || [])[0] || 'N/A'}`
).join('\n') || '  No alerts'}

========================================
Report generated by QoS Buddy v2.0
Esprit PIDEV · 4DS8
`;

    downloadFile(report, `qos_report_${boLabel}_${ts.replace(/[:]/g, '-')}.txt`, 'text/plain');
    setExported('report');
    setTimeout(() => setExported(null), 2000);
  };

  return (
    <div className="rounded-2xl border border-white/10 bg-gradient-to-br from-slate-900/80 to-slate-950/80 p-5">
      <div className="flex items-center gap-2 mb-4">
        <Download className="w-4 h-4 text-cyan-400" />
        <h4 className="text-sm font-semibold text-slate-200">Export Data</h4>
      </div>

      <div className="grid grid-cols-2 sm:grid-cols-4 gap-2">
        <button
          type="button"
          onClick={() => handleExportCSV('alerts')}
          disabled={!diagnosticAlerts?.length}
          className="flex flex-col items-center gap-1.5 p-3 rounded-xl border border-white/10 bg-white/5 hover:bg-white/10 transition-colors disabled:opacity-30"
        >
          <FileSpreadsheet className="w-5 h-5 text-emerald-400" />
          <span className="text-xs text-slate-300">Alerts CSV</span>
          {exported === 'alerts' && <span className="text-[10px] text-emerald-400">Downloaded!</span>}
        </button>

        <button
          type="button"
          onClick={() => handleExportCSV('kpis')}
          disabled={!overview?.trends?.length}
          className="flex flex-col items-center gap-1.5 p-3 rounded-xl border border-white/10 bg-white/5 hover:bg-white/10 transition-colors disabled:opacity-30"
        >
          <FileSpreadsheet className="w-5 h-5 text-blue-400" />
          <span className="text-xs text-slate-300">KPIs CSV</span>
          {exported === 'kpis' && <span className="text-[10px] text-emerald-400">Downloaded!</span>}
        </button>

        <button
          type="button"
          onClick={() => handleExportCSV('zones')}
          disabled={!overview?.zones?.length}
          className="flex flex-col items-center gap-1.5 p-3 rounded-xl border border-white/10 bg-white/5 hover:bg-white/10 transition-colors disabled:opacity-30"
        >
          <FileSpreadsheet className="w-5 h-5 text-amber-400" />
          <span className="text-xs text-slate-300">Zones CSV</span>
          {exported === 'zones' && <span className="text-[10px] text-emerald-400">Downloaded!</span>}
        </button>

        <button
          type="button"
          onClick={handleExportReport}
          className="flex flex-col items-center gap-1.5 p-3 rounded-xl border border-white/10 bg-white/5 hover:bg-white/10 transition-colors"
        >
          <FileText className="w-5 h-5 text-purple-400" />
          <span className="text-xs text-slate-300">Full Report</span>
          {exported === 'report' && <span className="text-[10px] text-emerald-400">Downloaded!</span>}
        </button>
      </div>
    </div>
  );
}
